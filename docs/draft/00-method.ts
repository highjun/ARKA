/**
 * ## 2단계 — 필드 검토
 *
 * `채택`·`부분 채택`한 인터페이스의 **모든** 필드·메서드가 대상이다. **뺀 것도 남긴다** —
 * 코드 없이 주석 여섯 줄만 놓고 `④ 뺌`으로 적는다. 목록에 없는 필드는 "뺐다"가 아니라 "안 봤다"다.
 *
 * 필드마다 바로 위에 여섯 줄을 순서대로 둔다. 한 줄이라도 비면 그 필드는 미검토다.
 *
 * 자리는 둘이다. **가져온 필드**는 코드가 있으므로 그 선언 위 `/** *&#47;`에 적고,
 * **`뺌`·`미룸`은 코드가 없으므로** 그 인터페이스 끝의 `뺀 것` 블록에 한 줄로 모은다.
 * 한 줄로 접더라도 여섯 칸은 그대로 다 적는다 — 접는 것은 자리지 내용이 아니다.
 *
 * 원본이 큰 경우(필드 수십 개) 1단계를 **묶음 단위로 잘게** 낸다. 1단계에서 묶음이 `기각`이면
 * 그 묶음의 필드는 2단계 행을 갖지 않는다 — 대신 **1단계 행이 덮는 필드 이름을 전부 적는다.**
 * 그래야 "안 봤다"와 "보고 버렸다"가 구분된다.
 *
 * ```text
 * ① 원본 뜻     이 필드가 무엇을 나타내나              ← 원본의 주석·타입·기본값
 * ② 원본 사용처  원본은 이것을 어느 코드 경로에서 읽나   ← 원본 저장소의 참조 두어 곳
 * ③ ARKA 시나리오 그 경로에 해당하는 일이 우리에게 있나  ← 있다 / 없다 / 나중에
 * ④ 판정        아래 어휘 하나
 * ⑤ 근거        ③에서 ④가 나온 이유 한 문장. 바꿨으면 원본과 무엇이 다른지
 * ⑥ 강제        이 판정을 누가 지키나
 * ```
 *
 * **③이 판정을 끌고 간다.** "원본에 있으니 가져온다"는 근거가 아니다 — 원본이 그 필드를 읽는 코드 경로가
 * ARKA에 있는지를 먼저 답하고, 그 답에서 판정이 나온다.
 */
export type FieldVerdict =
  /** 이름·타입·뜻 그대로. */
  | "그대로"
  /** 뜻은 같고 이름만 ARKA 관례로. */
  | "이름만"
  /** 타입·enum·선택성을 줄인다. 원본이 여러 배치를 지원하느라 넓게 둔 자리가 대개 여기다. */
  | "좁힘"
  /** 반대. 드물어야 하고 ⑤가 강해야 한다. */
  | "넓힘"
  /** 가져오지 않는다. ③이 "없다"여야 한다. */
  | "뺌"
  /** ③이 "나중에". 어느 feature에서 돌아올지 ⑤에 적는다. */
  | "미룸"
  /** 원본에 없는 ARKA 필드. ⑤에 "왜 원본은 필요 없었고 우리는 필요한가"를 적는다. */
  | "더함";

