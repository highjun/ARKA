/**
 * 오픈소스 계약을 본뜨는 방법 — 이 폴더의 파일들이 따르는 규칙.
 *
 * **이 폴더는 초안이다.** 판정은 사용자가 한다. 승인되기 전까지 `packages/*&#47;src/`·ADR·`CONVENTIONS.md`는
 * 건드리지 않는다. 승인된 뒤에야 계약 PR이 열리고, 그때 이 파일들의 검토 주석(①~⑥)은 걷어낸다 —
 * 코드에 출처를 남기지 않기로 했기 때문이다.
 *
 * 파일이 곧 표다. 별도 `.md` 대조표를 두지 않는다 — 표와 코드가 갈라져 표가 낡는 것을 막기 위해서다.
 * 한 feature가 파일 하나고, 파일 하나가 1단계(무엇을 가져오나)와 2단계(각 필드를 어떻게 바꾸나)를 함께 든다.
 */

