/**
 * ## 1단계 — feature 분류
 *
 * 원본의 인터페이스·타입을 하나씩 놓고 무엇을 가져올지 정한다. feature 파일의 머리 주석이 이 표를 든다.
 *
 * 열: `원본 이름` · `ARKA 대응`(지금 있는 자리 또는 `없음`) · `판정` · `사유`(한 문장).
 *
 * 사유는 ARKA 전제와 대조한 결과다 — 단일 사용자, PWA 클라이언트, 사용자 PC 한 대,
 * 터널 뒤라 앱이 인증을 모름, 데스크톱·모바일 기능 동등.
 */
